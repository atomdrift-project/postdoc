#!/usr/bin/env python3
"""Build a stub nono-py wheel so guarddog can be installed on FreeBSD.

guarddog confines itself with nono-py, a kernel-level sandbox (Landlock on
Linux, sandbox_init on macOS), and takes a hard dependency on it. nono has no
FreeBSD implementation and its Rust crate does not compile there either --
`nono 0.74.0`'s capability.rs references an undefined `key` on any non-Linux,
non-macOS target -- so `uvx guarddog` fails at install, long before any
detection could run. There is no newer release with a fix.

The sandbox is hardening, not detection: guarddog's rules are YARA
(`yara-python`), which works fine on FreeBSD. So the whole engine is available
once the dependency can be satisfied. This writes a pure-Python stand-in that
reports the platform as unsupported and refuses to do anything else, plus an
overrides file pinning nono-py to it. guarddog sees is_supported() == False and
requires --no-sandbox, which postdoc passes wherever nono cannot work (as
gauntlet, where this script comes from, does); nothing here ever pretends a
sandbox was applied.

Confinement is not lost on those hosts so much as relocated: there the
service's own confinement is what holds the scan.

Point pip at both outputs (the overrides file is also a constraints file) and
it resolves the stub instead of building the real crate:

    pip install --find-links <outdir> -c <outdir>/overrides.txt guarddog

The override pins the exact version rather than merely offering the stub,
because uv otherwise takes the highest compatible release -- and would go back
to building the real crate the day upstream publishes a new one. If guarddog
ever raises its floor above STUB_VERSION, resolution fails loudly, which is the
right way to find out that this needs revisiting.

Usage: nono-stub-wheel.py <outdir>
"""

import base64
import csv
import hashlib
import io
import os
import sys
import zipfile

# Must satisfy guarddog's `nono-py (>=0.15.0)`. Tracks the newest real release so
# the substitution stays honest about what it stands in for.
STUB_VERSION = "0.16.0"

MODULE = '''"""nono_py - unsupported-platform stub.

The real nono-py gives guarddog a kernel-level sandbox (Landlock on Linux,
sandbox_init on macOS). It has no FreeBSD implementation, and its Rust crate
does not compile there, so guarddog cannot be installed at all without a
stand-in for the dependency.

This reports the platform as unsupported and refuses to do anything else.
guarddog checks is_supported(), finds it False, and requires --no-sandbox
before it will scan. Nothing here ever pretends a sandbox was applied.

Installed by scripts/nono-stub-wheel.py. Not published anywhere.
"""

__version__ = "{version}"


def is_supported() -> bool:
    """No kernel-level sandbox is available on this platform."""
    return False


def _unsupported(*_args, **_kwargs):
    raise NotImplementedError(
        "nono_py is a stub on this platform: no kernel-level sandbox is "
        "available. Run guarddog with --no-sandbox, and confine it by other "
        "means."
    )


apply = _unsupported
sandboxed_exec = _unsupported
CapabilitySet = _unsupported
AccessMode = _unsupported
'''

METADATA = """Metadata-Version: 2.1
Name: nono-py
Version: {version}
Summary: Unsupported-platform stub for nono-py
"""

WHEEL = """Wheel-Version: 1.0
Generator: nono-stub-wheel
Root-Is-Purelib: true
Tag: py3-none-any
"""


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    outdir = sys.argv[1]
    os.makedirs(outdir, exist_ok=True)

    dist = f"nono_py-{STUB_VERSION}.dist-info"
    files = {
        "nono_py.py": MODULE.format(version=STUB_VERSION),
        f"{dist}/METADATA": METADATA.format(version=STUB_VERSION),
        f"{dist}/WHEEL": WHEEL,
    }

    # RECORD lists every file with its hash; the wheel is rejected without it.
    records = []
    for name, text in files.items():
        raw = text.encode()
        digest = base64.urlsafe_b64encode(hashlib.sha256(raw).digest()).rstrip(b"=")
        records.append((name, f"sha256={digest.decode()}", len(raw)))
    records.append((f"{dist}/RECORD", "", ""))
    buf = io.StringIO()
    csv.writer(buf, lineterminator="\n").writerows(records)
    files[f"{dist}/RECORD"] = buf.getvalue()

    wheel = os.path.join(outdir, f"nono_py-{STUB_VERSION}-py3-none-any.whl")
    tmp = wheel + ".new"
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zf:
        for name, text in sorted(files.items()):
            zf.writestr(name, text)
    os.replace(tmp, wheel)

    overrides = os.path.join(outdir, "overrides.txt")
    tmp = overrides + ".new"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write("# Generated by scripts/nono-stub-wheel.py.\n")
        fh.write("# Pins nono-py to the stub beside this file; see that script.\n")
        fh.write(f"nono-py=={STUB_VERSION}\n")
    os.replace(tmp, overrides)

    print(f"wrote {wheel}")
    print(f"wrote {overrides}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
